"""Write the Homebrew tap's formula and cask for one Eyrie release, from that release's
SHA256SUMS (docs/packaging.md §7.1). Stdlib only.

    python3 packaging/homebrew/render.py 0.2.0 /path/to/homebrew-eyrie

Writes Formula/eyrie-server.rb (server + web UI, macOS and Linux) and Casks/eyrie.rb (the
macOS app with its menu-bar widget) into the tap checkout. Commit and push the tap after.
"""
import subprocess
import sys
from pathlib import Path

REPO = "abrahamalen/eyrie"
HOMEPAGE = "https://alenabraham.me/eyrie/"


def sums(version: str) -> dict[str, str]:
    url = f"https://github.com/{REPO}/releases/download/v{version}/SHA256SUMS"
    # curl, not urllib: some Python builds (python.org's on macOS) ship without CA certificates.
    lines = subprocess.run(["curl", "-fsSL", url], capture_output=True, text=True, check=True).stdout.splitlines()
    return {name.lstrip("*"): digest for digest, name in (line.split(None, 1) for line in lines if line.strip())}


def formula(v: str, s: dict[str, str]) -> str:
    def block(arch: str, os_: str) -> str:
        name = f"eyrie-server-{v}-{os_}-{arch}.tar.gz"
        return (f'      url "https://github.com/{REPO}/releases/download/v{v}/{name}"\n'
                f'      sha256 "{s[name]}"')
    return f'''# Generated by eyrie's packaging/homebrew/render.py for v{v}; don't edit by hand.
class EyrieServer < Formula
  desc "Local control plane for AI coding tools: server and web UI, no widget"
  homepage "{HOMEPAGE}"
  version "{v}"
  license "MIT"

  on_macos do
    on_arm do
{block("aarch64", "macos")}
    end
    on_intel do
{block("x86_64", "macos")}
    end
  end

  on_linux do
    on_arm do
{block("aarch64", "linux")}
    end
    on_intel do
{block("x86_64", "linux")}
    end
  end

  def install
    libexec.install Dir["*"]
    # A wrapper, not a symlink: the bundled binary finds its libraries next to its real path.
    (bin/"eyrie-server").write_env_script libexec/"eyrie-server/eyrie-server",
                                          EYRIE_SERVER__UI_DIR: opt_libexec/"ui"
  end

  def caveats
    <<~EOS
      Run Eyrie in the background at login (launchd on macOS, systemd user unit on Linux):
        #{{opt_libexec}}/eyrie-server/eyrie-server service install --ui-dir #{{opt_libexec}}/ui
      then open http://127.0.0.1:8787 to finish setup. Re-run it after `brew upgrade`.
      Your data lives in ~/.eyrie and is never removed by Homebrew.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/eyrie-server --version")
  end
end
'''


def cask(v: str, s: dict[str, str]) -> str:
    arm, intel = s[f"Eyrie_{v}_aarch64.dmg"], s[f"Eyrie_{v}_x64.dmg"]
    return f'''# Generated by eyrie's packaging/homebrew/render.py for v{v}; don't edit by hand.
cask "eyrie" do
  arch arm: "aarch64", intel: "x64"

  version "{v}"
  sha256 arm:   "{arm}",
         intel: "{intel}"

  url "https://github.com/{REPO}/releases/download/v#{{version}}/Eyrie_#{{version}}_#{{arch}}.dmg"
  name "Eyrie"
  desc "Local control plane for AI coding tools, with a menu-bar widget"
  homepage "{HOMEPAGE}"

  depends_on macos: :ventura

  app "Eyrie.app"

  # The app isn't signed yet; Homebrew quarantines cask downloads, so clear the flag
  # (the same as right-click > Open after a browser download).
  postflight_steps do
    run "/usr/bin/xattr", args: ["-dr", "com.apple.quarantine", "{{{{appdir}}}}/Eyrie.app"]
  end

  uninstall quit: "me.alenabraham.eyrie"

  caveats <<~EOS
    Launch Eyrie once: it installs its background service and opens setup in your browser.
    Before uninstalling, use the menu's "Quit and remove service".
    Your data in ~/.eyrie is never removed.
  EOS
end
'''


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    v, tap = sys.argv[1].removeprefix("v"), Path(sys.argv[2])
    s = sums(v)
    (tap / "Formula").mkdir(parents=True, exist_ok=True)
    (tap / "Casks").mkdir(parents=True, exist_ok=True)
    (tap / "Formula/eyrie-server.rb").write_text(formula(v, s))
    (tap / "Casks/eyrie.rb").write_text(cask(v, s))
    print(f"wrote Formula/eyrie-server.rb and Casks/eyrie.rb for v{v} in {tap}")
